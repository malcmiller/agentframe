"""Token usage and finish reasons, shared by runs and model calls."""

from dataclasses import dataclass
from enum import StrEnum


class FinishReason(StrEnum):
    """Why a run or a model call finished.

    Attributes:
        COMPLETED: Finished normally with a complete result.
        LENGTH: The model stopped at its output token limit; output is truncated.
        REFUSED: The model refused the request.
        CONTENT_FILTER: A provider content filter stopped the output.
    """

    COMPLETED = "completed"
    LENGTH = "length"
    REFUSED = "refused"
    CONTENT_FILTER = "content_filter"


@dataclass(frozen=True)
class Usage:
    """Token usage for a run or model call. ``None`` means unknown, not zero.

    Attributes:
        input_tokens: Tokens sent to models.
        output_tokens: Tokens generated by models.
        total_tokens: Input plus output tokens.
        estimated: Whether the counts are estimates rather than reported values.
    """

    input_tokens: int | None
    output_tokens: int | None
    total_tokens: int | None
    estimated: bool
