"""``agentframe compose``: one development container per agent of ``agentframe.yaml``.

The command writes ``compose.yaml`` next to ``agentframe.yaml`` and, if there
is none yet, a ``Dockerfile`` that installs the project's wheels from
``dist/``. Each agent becomes one Compose service, named after the agent, that
runs ``agentframe run <app> --host 0.0.0.0 --port <port>`` and gets the same
environment ``agentframe dev`` gives its agents (see ``agentframe.dev``):

- ``AGENTFRAME_PUBLIC_URL`` and the registry ``AGENTFRAME_AGENTS`` use the
  service names, which other containers resolve, for example
  ``http://research-agent:8001``;
- ``AGENTFRAME_DEV=1`` and ``AGENTFRAME_ALLOW_HTTP_HOSTS`` (every service name)
  are the explicit development opt-in that lets the directory fetch cards over
  plain http between containers;
- API keys appear only as ``${RESEARCH_AGENT_API_KEY}`` references that Compose
  reads from an env file the user creates. No key is ever written.

Ports are published on ``127.0.0.1`` only, and each service starts after the
agents listed before it are healthy on ``/ready``, as with ``agentframe dev``.
"""

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import yaml
from a2a.utils.constants import AGENT_CARD_WELL_KNOWN_PATH

from agentframe.dev import (
    AGENTS_VARIABLE,
    ALLOW_HTTP_HOSTS_VARIABLE,
    API_KEYS_VARIABLE,
    DEV_VARIABLE,
    PUBLIC_URL_VARIABLE,
    REMOTE_KEYS_VARIABLE,
    format_pairs,
)
from agentframe.dev_server import CLIENT_CALLER, CLIENT_KEY_VARIABLE
from agentframe.errors import DefinitionError
from agentframe.hosting.app import READY_PATH
from agentframe.project import ProjectAgent, load_project

COMPOSE_FILE = "compose.yaml"
DOCKERFILE = "Dockerfile"

# python:3.13-slim, multi-platform image index, looked up on 2026-11-13.
# Update it deliberately, after testing, rather than following the tag.
BASE_IMAGE = (
    "python:3.13-slim@sha256:"
    "e48f59cdba69a3cbd9ed2cf0f348d90d45a8d350d98134cf1070bc106ee9ed90"
)

# HostConfig's default shutdown grace period, plus time for the process to exit.
_STOP_GRACE_PERIOD = "35s"

_COMPOSE_HEADER = """\
# Generated by `agentframe compose` from agentframe.yaml.
# DEVELOPMENT ONLY: AGENTFRAME_DEV=1 enables development API keys and plain
# http between containers. Do not deploy this file; production needs real
# authentication, HTTPS and secrets kept outside images.
# Set every ${...} variable below in a .env file next to this file; keys are
# never written here.
"""

DOCKERFILE_TEMPLATE = f"""\
# Generated by `agentframe compose`; edit freely, it is never overwritten.
# Build your project's wheel into dist/ first, for example `uv build`.
# The wheel must depend on agentframe-py[server].
FROM {BASE_IMAGE}
ENV PYTHONUNBUFFERED=1
WORKDIR /app
COPY dist/*.whl /tmp/wheels/
RUN python -m pip install --no-cache-dir /tmp/wheels/*.whl && rm -rf /tmp/wheels
USER 10001:10001
"""


@dataclass(frozen=True)
class ComposeResult:
    """What ``write_compose`` did.

    Args:
        written: The files it wrote.
        kept: An existing ``Dockerfile`` it left unchanged.
        variables: The key variables the user must set in the env file.
    """

    written: list[Path]
    kept: Path | None
    variables: list[str]


def key_variable(agent_name: str) -> str:
    """Return the env-file variable holding an agent's development API key.

    For example ``research-agent`` -> ``RESEARCH_AGENT_API_KEY``.
    """
    return agent_name.upper().replace("-", "_") + "_API_KEY"


def compose_document(agents: Sequence[ProjectAgent]) -> str:
    """Return the ``compose.yaml`` text for ``agents``.

    Args:
        agents: The project's agents, in ``agentframe.yaml`` order.

    Returns:
        The Compose file, development-labelled, with key references only.

    Raises:
        DefinitionError: An agent name starts with a digit, so it cannot name
            an environment variable.
    """
    for agent in agents:
        if agent.name[0].isdigit():
            raise DefinitionError(
                f"Agent '{agent.name}' cannot be used with agentframe compose: "
                "its key variable would start with a digit. Start the name "
                "with a letter."
            )
    services = {
        agent.name: _service(agent, agents, earlier=agents[:index])
        for index, agent in enumerate(agents)
    }
    body = yaml.safe_dump({"services": services}, sort_keys=False, width=1000)
    return _COMPOSE_HEADER + body


def write_compose(project_file: Path, *, force: bool = False) -> ComposeResult:
    """Write ``compose.yaml`` and, if missing, ``Dockerfile`` for a project.

    Both go next to ``project_file``. An existing ``Dockerfile`` is always
    kept, since it is the user's to edit.

    Args:
        project_file: The ``agentframe.yaml`` file.
        force: Overwrite an existing ``compose.yaml``.

    Returns:
        The files written, a kept ``Dockerfile`` and the variables to set.

    Raises:
        DefinitionError: The project file is invalid, or ``compose.yaml``
            exists and ``force`` is false. Nothing is written then.
    """
    agents = load_project(project_file)
    document = compose_document(agents)
    directory = project_file.resolve().parent
    compose_path = directory / COMPOSE_FILE
    dockerfile_path = directory / DOCKERFILE
    if compose_path.exists() and not force:
        raise DefinitionError(
            f"{compose_path} already exists; pass --force to overwrite it."
        )
    compose_path.write_text(document)
    written = [compose_path]
    kept = dockerfile_path if dockerfile_path.exists() else None
    if kept is None:
        dockerfile_path.write_text(DOCKERFILE_TEMPLATE)
        written.append(dockerfile_path)
    variables = [key_variable(agent.name) for agent in agents]
    return ComposeResult(written, kept, [*variables, CLIENT_KEY_VARIABLE])


def _service(
    agent: ProjectAgent,
    agents: Sequence[ProjectAgent],
    *,
    earlier: Sequence[ProjectAgent],
) -> dict[str, object]:
    others = [other for other in agents if other.name != agent.name]
    accepted = {other.name: _reference(key_variable(other.name)) for other in others}
    accepted[CLIENT_CALLER] = _reference(CLIENT_KEY_VARIABLE)
    own_key = _reference(key_variable(agent.name))
    service: dict[str, object] = {
        "build": ".",
        "command": [
            "agentframe",
            "run",
            agent.app,
            "--host",
            "0.0.0.0",
            "--port",
            str(agent.port),
        ],
        "ports": [f"127.0.0.1:{agent.port}:{agent.port}"],
        "environment": {
            DEV_VARIABLE: "1",
            PUBLIC_URL_VARIABLE: _service_url(agent),
            AGENTS_VARIABLE: format_pairs(
                {
                    each.name: _service_url(each) + AGENT_CARD_WELL_KNOWN_PATH
                    for each in agents
                }
            ),
            ALLOW_HTTP_HOSTS_VARIABLE: ",".join(each.name for each in agents),
            API_KEYS_VARIABLE: format_pairs(accepted),
            REMOTE_KEYS_VARIABLE: format_pairs(
                {other.name: own_key for other in others}
            ),
        },
        "healthcheck": {
            # The slim image has no curl; urlopen fails on any non-2xx answer.
            "test": [
                "CMD",
                "python",
                "-c",
                "import urllib.request; urllib.request.urlopen("
                f"'http://127.0.0.1:{agent.port}{READY_PATH}')",
            ],
            "interval": "2s",
            "timeout": "2s",
            "retries": 15,
        },
        "stop_grace_period": _STOP_GRACE_PERIOD,
    }
    if earlier:
        service["depends_on"] = {
            each.name: {"condition": "service_healthy"} for each in earlier
        }
    return service


def _service_url(agent: ProjectAgent) -> str:
    return f"http://{agent.name}:{agent.port}"


def _reference(variable: str) -> str:
    # Compose stops with this message if the variable is unset or empty.
    return f"${{{variable}:?set {variable} in .env}}"
